use super::*;

const RECEIPT_FIXTURE: [(&str, &str); 6] = [
    (
        "compliance/licenses/upstream/example/LICENSE",
        "upstream license\n",
    ),
    ("docs/dependencies/example/README.md", "dependency docs\n"),
    (
        "src/foundation/example/Cargo.toml",
        "[package]\nname='example'\nversion='1.0.0'\n",
    ),
    (
        "src/foundation/example/src/lib.rs",
        "pub const VALUE:u8=1;\n",
    ),
    (
        "src/foundation/example/src/target/data.rs",
        "pub const DATA:u8=1;\n",
    ),
    ("test/example/case.rs", "#[test]\nfn case() {}\n"),
];

fn fixture() -> io::Result<tempfile::TempDir> {
    let repository = tempfile::tempdir()?;
    for (name, contents) in RECEIPT_FIXTURE {
        let path = repository.path().join(name);
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, contents)?;
    }
    Ok(repository)
}

#[test]
fn full_verification_preserves_existing_receipt_encoding_and_source_coverage() -> io::Result<()> {
    let repository = fixture()?;
    for ignored in [
        "src/foundation/example/target/generated",
        "test/__pycache__/generated",
        "docs/dependencies/.git/generated",
        "compliance/licenses/upstream/.pytest_cache/generated",
    ] {
        let path = repository.path().join(ignored);
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, "excluded generated bytes")?;
    }
    let inputs = SnapshotFiles::default().verification_inputs(repository.path())?;
    assert_eq!(
        inputs.keys().map(String::as_str).collect::<Vec<_>>(),
        RECEIPT_FIXTURE.map(|(name, _)| name)
    );
    // Frozen from the previous path-NUL-SHA256-newline receipt encoding,
    // independently calculated with Python hashlib over these fixture bytes.
    assert_eq!(
        digest(&inputs),
        "0f5df871b4fdcb32273dc2babdb0254c9c139af3b25a0589be717c0b57ac6e36"
    );
    Ok(())
}

#[test]
fn fresh_snapshots_detect_changes_in_every_verification_category() -> io::Result<()> {
    let repository = fixture()?;
    let before = SnapshotFiles::default().verification_inputs(repository.path())?;
    for (name, original) in RECEIPT_FIXTURE {
        let path = repository.path().join(name);
        fs::write(&path, "changed source bytes")?;
        let after = SnapshotFiles::default().verification_inputs(repository.path())?;
        assert_ne!(after[name], before[name], "{name}");
        assert_ne!(digest(&after), digest(&before), "{name}");
        fs::write(path, original)?;
    }
    Ok(())
}

#[test]
fn input_limits_reject_oversized_files_and_excess_file_counts() -> io::Result<()> {
    let repository = tempfile::tempdir()?;
    let oversized = repository.path().join("oversized");
    fs::File::create(&oversized)?.set_len(MAX_FILE + 1)?;
    assert!(read(&oversized).is_err());
    fs::remove_file(oversized)?;
    fs::write(repository.path().join("first"), "first")?;
    fs::write(repository.path().join("second"), "second")?;
    assert!(walk(repository.path(), 1).is_err());
    assert_eq!(walk(repository.path(), 2)?.len(), 2);
    Ok(())
}

#[test]
fn authored_web_inputs_cover_custom_directories_and_exclude_generated_material() -> io::Result<()> {
    let repository = tempfile::tempdir()?;
    let web = repository.path();
    let authored = [
        "custom/Cargo.toml",
        "custom/target/source.js",
        "custom/widgets/entry.js",
        "index.html",
    ];
    for name in authored.into_iter().chain([
        "pkg/bridge.js",
        "dist/old.js",
        "node_modules/package/entry.js",
        "custom/node_modules/package/entry.js",
        ".rust-web-stage-example/pkg/bridge.js",
        ".previous-example/assets/old.js",
        "custom/__pycache__/old",
    ]) {
        let path = web.join(name);
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, "source or generated bytes")?;
    }
    let found = web_paths(web, web)?
        .into_iter()
        .map(|path| relative(path.strip_prefix(web).unwrap()).unwrap())
        .collect::<Vec<_>>();
    assert_eq!(found, authored);
    assert!(web_relative(Path::new("pkg/bridge.js"), true).is_ok());
    for generated in [
        "pkg/bridge.js",
        "dist/old.js",
        "node_modules/package/entry.js",
        "custom/node_modules/package/entry.js",
    ] {
        assert!(
            web_relative(Path::new(generated), false).is_err(),
            "{generated}"
        );
    }
    assert!(web_relative(Path::new("dist/old.js"), true).is_err());
    Ok(())
}

#[cfg(unix)]
#[test]
fn verification_rejects_linked_sources_and_special_objects() -> io::Result<()> {
    use std::os::unix::{fs::symlink, net::UnixListener};

    let repository = tempfile::tempdir()?;
    let root = repository.path();
    fs::create_dir(root.join("test"))?;
    let source = root.join("test/source");
    fs::write(&source, "physical source")?;
    fs::hard_link(&source, root.join("test/alias"))?;
    assert!(SnapshotFiles::default().verification_inputs(root).is_err());
    fs::remove_file(root.join("test/alias"))?;
    symlink("test", root.join("linked-directory"))?;
    assert!(read(&root.join("linked-directory/source")).is_err());
    let socket = root.join("test/socket");
    let _listener = UnixListener::bind(&socket)?;
    assert!(verification_paths(root).is_err());
    fs::remove_file(socket)?;
    fs::create_dir(root.join("src"))?;
    symlink("missing", root.join("src/foundation"))?;
    assert!(verification_paths(root).is_err());
    Ok(())
}

#[test]
fn source_hashes_preserve_sha256_lowercase_and_leading_zeroes() {
    assert_eq!(
        sha(b""),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855"
    );
    assert_eq!(
        sha(b"abc"),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
    );
    let bytes: Vec<_> = (0..=u8::MAX).collect();
    let encoded = hex_digest(&bytes);
    assert_eq!(encoded.len(), bytes.len() * 2);
    for (byte, pair) in bytes.iter().zip(encoded.as_bytes().as_chunks::<2>().0) {
        assert_eq!(pair, format!("{byte:02x}").as_bytes());
    }
}

#[test]
#[ignore = "manual release-profile source digest benchmark"]
fn source_digest_benchmark() {
    use std::{hint::black_box, time::Instant};

    fn previous_hex(bytes: &[u8]) -> String {
        bytes.iter().map(|byte| format!("{byte:02x}")).collect()
    }
    fn previous_sha(bytes: &[u8]) -> String {
        previous_hex(&Sha256::digest(bytes))
    }
    fn measure(operation: fn(&[u8]) -> String, bytes: &[u8]) -> u128 {
        let started = Instant::now();
        for _ in 0..20_000 {
            black_box(operation(black_box(bytes)));
        }
        started.elapsed().as_micros()
    }

    let digest = Sha256::digest(b"source digest benchmark");
    let small = b"pub fn main() {}\n";
    let file = vec![b'x'; 4096];
    for (label, bytes, previous, current) in [
        (
            "hex-only",
            digest.as_slice(),
            previous_hex as fn(&[u8]) -> String,
            hex_digest as fn(&[u8]) -> String,
        ),
        ("sha-empty", b"".as_slice(), previous_sha, sha),
        ("sha-small", small.as_slice(), previous_sha, sha),
        ("sha-4096", file.as_slice(), previous_sha, sha),
    ] {
        assert_eq!(previous(bytes), current(bytes));
        for round in 0..5 {
            let (before, after) = if round % 2 == 0 {
                (measure(previous, bytes), measure(current, bytes))
            } else {
                let after = measure(current, bytes);
                (measure(previous, bytes), after)
            };
            eprintln!(
                "{label}: round={round} samples=20000 bytes={} previous_us={before} current_us={after}",
                bytes.len()
            );
        }
    }
}
